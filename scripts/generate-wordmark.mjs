// Generates the Roam wordmark from Urbanist Black glyph outlines.
//   node scripts/generate-wordmark.mjs
// Outputs (never edit by hand - change this script and rerun):
//   assets/brand/roam-wordmark.svg
//   src/components/ui/wordmark-path.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import opentype from "opentype.js";

const TEXT = "roam";
const FONT_SIZE = 100; // path units; the component scales to any height
const TRACKING_EM = -0.02; // extra space between glyphs, in em
const DECIMALS = 2;
const INK = "#0B0B1A"; // foreground token

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontFile = readFileSync(join(root, "assets/brand/source/Urbanist-Black.ttf"));
const font = opentype.parse(fontFile.buffer.slice(fontFile.byteOffset, fontFile.byteOffset + fontFile.byteLength));

const scale = FONT_SIZE / font.unitsPerEm;
const glyphs = font.stringToGlyphs(TEXT);
const path = new opentype.Path();
let x = 0;

glyphs.forEach((glyph, i) => {
  path.extend(glyph.getPath(x, 0, FONT_SIZE));
  const next = glyphs[i + 1];
  if (next) {
    x += glyph.advanceWidth * scale + font.getKerningValue(glyph, next) * scale + TRACKING_EM * FONT_SIZE;
  }
});

// Move the tight bounding box to the origin.
const box = path.getBoundingBox();
for (const cmd of path.commands) {
  for (const [kx, ky] of [["x", "y"], ["x1", "y1"], ["x2", "y2"]]) {
    if (kx in cmd) {
      cmd[kx] -= box.x1;
      cmd[ky] -= box.y1;
    }
  }
}

const round = (n) => Number(n.toFixed(DECIMALS));
const width = round(box.x2 - box.x1);
const height = round(box.y2 - box.y1);

// opentype.js 2.0's toPathData emits NaN for some values, so serialize ourselves.
const points = { M: ["x", "y"], L: ["x", "y"], Q: ["x1", "y1", "x", "y"], C: ["x1", "y1", "x2", "y2", "x", "y"], Z: [] };
const d = path.commands
  .map((cmd) => cmd.type + points[cmd.type].map((k) => round(cmd[k])).join(" "))
  .join("");
if (d.includes("NaN")) throw new Error("wordmark path contains NaN");
const header = "Generated by scripts/generate-wordmark.mjs - do not edit.";

writeFileSync(
  join(root, "assets/brand/roam-wordmark.svg"),
  `<!-- ${header} -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-label="roam">\n  <path fill="${INK}" d="${d}"/>\n</svg>\n`,
);

writeFileSync(
  join(root, "src/components/ui/wordmark-path.ts"),
  `// ${header}\nexport const wordmark = {\n  width: ${width},\n  height: ${height},\n  d: "${d}",\n} as const;\n`,
);

console.log(`wordmark: ${width} x ${height} (tracking ${TRACKING_EM}em)`);
